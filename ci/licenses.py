#!/usr/bin/env python3
"""Generate notices for Go and the modules linked into all supported targets."""
import argparse
import json
import os
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
modules = {}
decoder = json.JSONDecoder()
for target in ('linux/amd64', 'linux/arm64', 'darwin/amd64', 'darwin/arm64'):
    system, architecture = target.split('/')
    env = dict(os.environ, GOOS=system, GOARCH=architecture, CGO_ENABLED='0')
    raw = subprocess.check_output(['go', 'list', '-deps', '-json', '.'], cwd=root, env=env, text=True)
    while raw.strip():
        value, length = decoder.raw_decode(raw.lstrip())
        raw = raw.lstrip()[length:]
        module = value.get('Module', {})
        if module and not module.get('Main'):
            modules[module['Path']] = module
goroot = Path(subprocess.check_output(['go', 'env', 'GOROOT'], text=True).strip())
parts = ['Third-party notices for atmos-openbao-auth\n\nGenerated by ci/licenses.py.\n',
         '\n=== Go standard library ===\n\n' + (goroot / 'LICENSE').read_text()]
for name, module in sorted(modules.items()):
    files = sorted(path for path in Path(module['Dir']).iterdir()
                   if path.is_file() and path.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE', 'COPYRIGHT')))
    if not files:
        raise RuntimeError('Missing upstream license for ' + name)
    parts.append('\n=== ' + name + '@' + module['Version'] + ' ===\n')
    for path in files:
        parts.append('\n--- ' + path.name + ' ---\n\n' + path.read_text())
text = '\n'.join(parts).rstrip() + '\n'
destination = root / 'THIRD_PARTY_NOTICES.txt'
if args.check:
    if not destination.is_file() or destination.read_text() != text:
        raise SystemExit('Third-party notices need regeneration: python3 ci/licenses.py')
    print('Third-party notices match all release targets')
else:
    destination.write_text(text)
